  const KEY = "tb.lang";
  function detect() {
    try { const saved = localStorage.getItem(KEY); if (saved && STRINGS[saved]) return saved; } catch {}
    const langs = navigator.languages || [navigator.language || "en"];
    return langs.some((l) => /^(he|iw)\b/i.test(l)) ? "he" : "en";
  }
  let lang = detect();

  function t(key, vars) {
    let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  }
  // Fills every element marked data-i18n (text), data-i18n-placeholder, -title or -aria-label.
  function applyToDom(root = document) {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "he" ? "rtl" : "ltr";
    document.title = t("app.name");
    root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
    for (const attr of ["placeholder", "title", "aria-label"]) {
      root.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`))));
    }
  }
  function setLang(next) {
    lang = next;
    try { localStorage.setItem(KEY, next); } catch {}
    applyToDom();
  }

  window.i18n = {
    t, applyToDom, setLang,
    get lang() { return lang; },
    get locale() { return lang === "he" ? "he-IL" : undefined; },
  };
